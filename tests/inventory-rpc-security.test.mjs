import test from 'node:test';
import assert from 'node:assert/strict';
import { readFile } from 'node:fs/promises';
import { pathToFileURL } from 'node:url';

test('hardened inventory RPCs preserve stock checks, closing rules and name resolution', {
  skip: !process.env.INVENT_AUDIT_PGLITE_PATH,
}, async (t) => {
  const { PGlite } = await import(pathToFileURL(process.env.INVENT_AUDIT_PGLITE_PATH).href);
  const db = new PGlite();
  try {
    await db.exec(`
      create role anon;
      create role authenticated;
      create role service_role bypassrls;
      create table public.invent_parent_assets (
        id text primary key, category text, category_id integer, generic_name text, safety_stock integer
      );
      create table public.invent_child_assets (
        id bigint primary key, parent_id text references public.invent_parent_assets(id),
        opening_stock numeric default 0, fiscal_year_closed_at date, is_active boolean default true
      );
      create table public.invent_stock_movements (
        id bigint generated by default as identity primary key,
        child_asset_id bigint references public.invent_child_assets(id),
        movement_date date, movement_type text, quantity numeric, actual_delivery_price numeric,
        expiration_date date, lot_number text, staff_code integer, staff_name text, memo text
      );
      create table public.invent_fiscal_snapshots (
        id bigint generated by default as identity primary key,
        child_asset_id bigint references public.invent_child_assets(id), fiscal_year integer,
        opening_stock numeric, closing_stock numeric, closed_at date, unique(child_asset_id, fiscal_year)
      );
      alter table public.invent_parent_assets enable row level security;
      alter table public.invent_child_assets enable row level security;
      alter table public.invent_stock_movements enable row level security;
      alter table public.invent_fiscal_snapshots enable row level security;
      create policy staff_access on public.invent_parent_assets to authenticated using (true) with check (true);
      create policy staff_access on public.invent_child_assets to authenticated using (true) with check (true);
      create policy staff_access on public.invent_stock_movements to authenticated using (true) with check (true);
      create policy staff_access on public.invent_fiscal_snapshots to authenticated using (true) with check (true);
      grant select, insert, update, delete on all tables in schema public to authenticated, service_role;
      grant usage, select on all sequences in schema public to authenticated, service_role;
      create schema untrusted;
      create function untrusted.hashtext(text) returns integer language plpgsql as
        $$ begin raise exception 'Untrusted function was called'; end $$;
      grant usage on schema untrusted to authenticated;
    `);
    for (const file of ['create_parent_asset_rpc.sql', 'register_movement_rpc.sql', 'update_movement_rpc.sql', 'year_end_update_rpc.sql']) {
      await db.exec(await readFile(new URL(`../outputs/supabase_migration/${file}`, import.meta.url), 'utf8'));
    }
    const signatures = [
      'public.invent_create_parent_asset(text, integer, text)',
      'public.invent_register_movement(bigint, date, text, numeric, numeric, date, text, integer, text, text)',
      'public.invent_update_movement(bigint, bigint, date, text, numeric, numeric, date, text, integer, text, text)',
      'public.invent_year_end_update(date, boolean)',
    ];
    // Emulate the legacy settings, then verify the migration can be reapplied.
    for (const signature of signatures) {
      await db.exec(`alter function ${signature} reset search_path; grant execute on function ${signature} to public, anon;`);
    }
    const bodyHashes = () => db.query("select proname, md5(prosrc) as hash from pg_proc where proname like 'invent_%' order by proname");
    const before = (await bodyHashes()).rows;
    const sql = await readFile(new URL('../supabase/migrations/20261024084429_harden_inventory_rpc_functions.sql', import.meta.url), 'utf8');
    await db.exec(sql);
    await db.exec(sql);
    assert.deepEqual((await bodyHashes()).rows, before);

    await t.test('only authenticated and service roles can call the RPCs', async () => {
      for (const signature of signatures) {
        const permission = (await db.query(`select has_function_privilege('anon', $1, 'EXECUTE') as anon,
          has_function_privilege('authenticated', $1, 'EXECUTE') as staff,
          has_function_privilege('service_role', $1, 'EXECUTE') as service`, [signature])).rows[0];
        assert.deepEqual(permission, { anon: false, staff: true, service: true });
      }
      const functions = (await db.query("select proconfig, prosecdef from pg_proc where proname like 'invent_%'")).rows;
      assert.equal(functions.length, 4);
      assert.ok(functions.every((fn) => fn.proconfig.includes('search_path=""') && fn.prosecdef === false));
      await db.exec('set role anon;');
      for (const statement of [
        "select * from public.invent_create_parent_asset('分類', 1)",
        "select * from public.invent_register_movement(1, '2026-10-24', 'in', 1)",
        "select * from public.invent_update_movement(1, 1, '2026-10-24', 'in', 1)",
        "select public.invent_year_end_update('2027-06-30', true)",
      ]) await assert.rejects(db.exec(statement), (error) => error.code === '42501');
      await db.exec('reset role;');
    });

    await t.test('parent IDs are generated even with an untrusted caller search path', async () => {
      await db.exec('set role authenticated; set search_path to untrusted, public, pg_catalog;');
      const parent = (await db.query("select * from public.invent_create_parent_asset('分類', 1, 'テスト品目')")).rows[0];
      assert.equal(parent.id, 'P-0001');
      await db.exec("insert into public.invent_child_assets (id, parent_id, opening_stock) values (1, 'P-0001', 10), (2, 'P-0001', 0);");
    });

    let outboundId;
    await t.test('movement registration and edits still prevent negative stock', async () => {
      const inbound = (await db.query("select * from public.invent_register_movement(1, '2026-10-24', 'in', 5, 100)")).rows[0];
      const outbound = (await db.query("select * from public.invent_register_movement(1, '2026-10-24', 'out', 3)")).rows[0];
      outboundId = outbound.id;
      assert.equal(Number(inbound.actual_delivery_price), 100);
      assert.equal(Number(outbound.actual_delivery_price), 0);
      await assert.rejects(db.exec("select * from public.invent_register_movement(1, '2026-10-24', 'out', 99)"), /マイナス/);
      const updated = (await db.query("select * from public.invent_update_movement($1, 1, '2026-10-24', 'out', 4)", [outboundId])).rows[0];
      assert.equal(Number(updated.quantity), 4);
      await assert.rejects(db.query("select * from public.invent_update_movement($1, 2, '2026-10-24', 'out', 4)", [outboundId]), /マイナス/);
      assert.equal((await db.query('select count(*) as total from public.invent_stock_movements')).rows[0].total, 2);
      assert.equal(Number((await db.query('select child_asset_id from public.invent_stock_movements where id = $1', [outboundId])).rows[0].child_asset_id), 1);
    });

    await t.test('year-end dry run, closing and closed-period guards still work', async () => {
      const preview = (await db.query("select public.invent_year_end_update('2027-06-30', true) as result")).rows[0].result;
      assert.equal(preview.asset_count, 2);
      assert.equal(preview.rows.find((row) => row.id === 1).closing, 11);
      assert.equal((await db.query('select count(*) as total from public.invent_fiscal_snapshots')).rows[0].total, 0);
      const closed = (await db.query("select public.invent_year_end_update('2027-06-30', false) as result")).rows[0].result;
      assert.equal(closed.snapshot_count, 2);
      assert.equal(closed.updated_count, 2);
      assert.equal(Number((await db.query('select opening_stock from public.invent_child_assets where id = 1')).rows[0].opening_stock), 11);
      await assert.rejects(db.exec("select * from public.invent_register_movement(1, '2026-10-24', 'in', 1)"), /締め済み/);
      await assert.rejects(db.query("select * from public.invent_update_movement($1, 1, '2026-10-24', 'out', 4)", [outboundId]), /締め済み/);
      const repeatedPreview = (await db.query("select public.invent_year_end_update('2027-06-30', true) as result")).rows[0].result;
      assert.equal(repeatedPreview.rows.find((row) => row.id === 1).closing, 11);
    });
  } finally {
    await db.close();
  }
});
